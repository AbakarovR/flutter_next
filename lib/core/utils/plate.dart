/// Приводит госномер к единому виду: верхний регистр, без пробелов,
/// латинские буквы, похожие на кириллические, заменяются на кириллицу.
///
/// Зачем: мастер вводит «a123bc», «А123ВС» или «A 123 BC» — это один и тот
/// же номер. Без нормализации поиск не найдёт машину из-за латинской «A»
/// вместо русской «А». Применяем и при сохранении, и при поиске.
String normalizePlate(String input) {
  const lookalikes = {
    'A': 'А',
    'B': 'В',
    'E': 'Е',
    'K': 'К',
    'M': 'М',
    'H': 'Н',
    'O': 'О',
    'P': 'Р',
    'C': 'С',
    'T': 'Т',
    'Y': 'У',
    'X': 'Х',
  };
  final upper = input.toUpperCase().replaceAll(RegExp(r'\s+'), '');
  return upper.split('').map((ch) => lookalikes[ch] ?? ch).join();
}

/// Обычный российский регистрационный номер легкового автомобиля:
/// А123ВС77 или А123ВС777.
bool isValidPlate(String input) => RegExp(
  r'^[АВЕКМНОРСТУХ]\d{3}[АВЕКМНОРСТУХ]{2}\d{2,3}$',
).hasMatch(normalizePlate(input));
